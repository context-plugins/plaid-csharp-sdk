using System.Text.Json.Serialization;
using ThePlaidApi.Core.Models;
using ThePlaidApi.Models.Enums;

namespace ThePlaidApi.Models;

/// <summary>
/// An object representing metadata from the end user's uploaded document.
/// </summary>
public record DocumentMetadata
{
    /// <summary>
    /// The name of the document.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("name")]
    public string? Name { get; init; }

    /// <summary>
    /// The processing status of the document.
    /// <para>
    /// <c>PROCESSING_COMPLETE</c>: The document was successfully processed.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_ERROR</c>: The document could not be processed. Possible causes include: The document was an unacceptable document type such as an offer letter or bank statement, the document image was cropped or blurry, or the document was corrupted.
    /// </para>
    /// <para>
    /// <c>UNKNOWN</c> or <c>null</c>: An internal error occurred. If this happens repeatedly, contact support or your Plaid account manager.
    /// </para>
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("status")]
    public string? Status { get; init; }

    /// <summary>
    /// An identifier of the document that is also present in the paystub response.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("doc_id")]
    public string? DocId { get; init; }

    /// <summary>
    /// The type of document.
    /// <para>
    /// <c>DOCUMENT_TYPE_PAYSTUB</c>: A paystub.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_BANK_STATEMENT</c>: A bank statement.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_US_TAX_W2</c>: A W-2 wage and tax statement provided by a US employer reflecting wages earned by the employee.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_US_MILITARY_ERAS</c>: An electronic Retirement Account Statement (eRAS) issued by the US military.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_US_MILITARY_LES</c>: A Leave and Earnings Statement (LES) issued by the US military.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_US_MILITARY_CLES</c>: A Civilian Leave and Earnings Statement (CLES) issued by the US military.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_GIG</c>: Used to indicate that the income is related to gig work. Does not necessarily correspond to a specific document type.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_NONE</c>: Used to indicate that there is no underlying document for the data.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_US_TAX_1099_MISC</c>: A Form 1099-MISC information return reporting miscellaneous income.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_US_TAX_1099_K</c>: A Form 1099-K information return reporting payment card and third-party network transactions.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_PLAID_GENERATED_PAYSTUB_PDF</c>: Used to indicate that the PDF for the paystub was generated by Plaid.
    /// </para>
    /// <para>
    /// <c>DOCUMENT_TYPE_US_STUDENT_I20</c>: A Form I-20 Certificate of Eligibility for Nonimmigrant Student Status.
    /// </para>
    /// <para>
    /// <c>UNKNOWN</c>: Document type could not be determined.
    /// </para>
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("doc_type")]
    public DocType? DocType { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
