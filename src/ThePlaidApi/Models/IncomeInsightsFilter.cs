using System.Collections.Generic;
using System.Text.Json.Serialization;
using ThePlaidApi.Core.Models;

namespace ThePlaidApi.Models;

/// <summary>
/// Filters the returned income streams based on the specified income categories. If no filters are requested, streams from the following default set of categories are returned:
/// - <c>EARNED_INCOME.*</c> (<c>EARNED_INCOME.SALARY</c>, <c>EARNED_INCOME.GIG_ECONOMY</c>, <c>EARNED_INCOME.SELF_EMPLOYED</c>)
/// - <c>BENEFITS.DISABILITY</c>
/// - <c>RETIREMENT.*</c> (<c>RETIREMENT.GOVERNMENT_DERIVED</c>, <c>RETIREMENT.PRIVATE_RETIREMENT</c>, <c>RETIREMENT.PLAN_DISTRIBUTION</c>)
/// <para>
/// The final list of income categories is generated by adding the <c>included_categories</c>, then removing the <c>excluded_categories</c>. Priority is given to <c>excluded_categories</c> in the case of collisions.
/// </para>
/// <para>
/// Filter patterns supported:
/// - <c>*</c>: All categories
/// - <c>PRIMARY.*</c>: All categories within the specified primary category
/// - <c>PRIMARY.SECONDARY</c>: A specific income category
/// </para>
/// <para>
/// For a list of income categories, see the <see href="https://plaid.com/documents/income-v2-category-taxonomy.csv">Income V2 Category Taxonomy</see>.
/// </para>
/// </summary>
public record IncomeInsightsFilter
{
    /// <summary>
    /// Includes income streams matching the specified categories.
    /// </summary>
    [JsonPropertyName("included_categories")]
    public required IReadOnlyList<string> IncludedCategories { get; init; }

    /// <summary>
    /// Excludes income streams matching the specified categories.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("excluded_categories")]
    public IReadOnlyList<string>? ExcludedCategories { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
